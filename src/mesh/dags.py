"""Render the Airflow DAG (Amazon MWAA) from the contracts: one daily DAG, one task per data product, task
dependencies from the declared inputs. The file is generated and committed; CI fails when it is stale
(``mesh dags render --check``), so a new product or input never needs a hand-written DAG change."""

from __future__ import annotations

import json

from mesh.contracts import Registry

TEMPLATE = '''"""Generated by `mesh dags render` from products/*.yaml. Do not edit by hand."""

from __future__ import annotations

from datetime import timedelta

import pendulum
from airflow import DAG

try:  # Airflow 3
    from airflow.providers.standard.operators.python import PythonOperator
except ImportError:  # Airflow 2 (MWAA 2.10)
    from airflow.operators.python import PythonOperator

PRODUCTS = __PRODUCTS__


def run(product: str, ds: str, **_: object) -> None:
    from mesh.airflow_tasks import run_product

    run_product(product, ds)


with DAG(
    dag_id="mesh_daily",
    description="Ingest, transform, check and publish every data product for the previous day",
    schedule="0 2 * * *",
    start_date=pendulum.datetime(2026, 7, 1, tz="UTC"),
    catchup=False,
    max_active_runs=1,
    default_args={"owner": "data-platform", "retries": 2, "retry_delay": timedelta(minutes=5)},
    tags=["mesh", "data-products"],
) as dag:
    tasks = {
        product: PythonOperator(
            task_id=product.replace(".", "__"),
            python_callable=run,
            op_kwargs={"product": product},
            doc_md=f"Owner: {spec['owner']}. Freshness SLA: {spec['sla_hours']} h. Contract v{spec['version']}.",
        )
        for product, spec in PRODUCTS.items()
    }
    for product, spec in PRODUCTS.items():
        for upstream in spec["inputs"]:
            if upstream in tasks:
                tasks[upstream] >> tasks[product]
'''


def render(registry: Registry) -> str:
    spec = {
        p: {
            "inputs": registry[p].inputs,
            "owner": registry[p].owner,
            "sla_hours": registry[p].sla.freshness_hours,
            "version": registry[p].version,
        }
        for p in registry.order()
    }
    return TEMPLATE.replace("__PRODUCTS__", json.dumps(spec, indent=4))
